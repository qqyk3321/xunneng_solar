import { readFile, writeFile } from "node:fs/promises";
import { build } from "esbuild";

// Bundle the same optimizer/pricing code used by the UI, with just its fixed
// generation model. Deno requires explicit imports; this avoids a second engine.
const manifest = JSON.parse(await readFile("lib/solution-suggest/model-table-manifest.json", "utf8"));
const table = JSON.parse(await readFile(`public${manifest.url}`, "utf8"));
const model = table.models.find(model => model.id === "antigua/south/tilt-20" && model.source === "pvwatts");
if (!model) throw new Error("Missing fixed generation model");
const result = await build({
  stdin: { contents: `
    import { optimizeSystem, PROFILES } from './lib/solution-suggest/optimizer';
    import { estimateQuoteXcd, parsePricingValues, PRICING_FIELDS } from './lib/quote-pricing/model';
    const model = ${JSON.stringify(model)};
    export function calculateQuote(monthlyKwh, profile, pricing) {
      if (!Object.hasOwn(PROFILES, profile) || !Number.isFinite(monthlyKwh) || monthlyKwh <= 0 || monthlyKwh > 1000000) throw new Error('Invalid energy inputs');
      const values = parsePricingValues(Object.fromEntries(PRICING_FIELDS.map(field => [field.key, pricing[field.key]])));
      const equipment = optimizeSystem(model, monthlyKwh, PROFILES[profile].values);
      return estimateQuoteXcd(values, equipment);
    }
  `, resolveDir: process.cwd(), sourcefile: "webhook-quote-entry.js" },
  bundle: true, format: "esm", platform: "neutral", target: "es2022", write: false,
  banner: { js: `// Generated by scripts/solar/build-webhook-quote.mjs. Do not edit.\n// Model table: ${manifest.version}` },
});
const output = "supabase/functions/tally-webhook/quote-engine.js";
const content = result.outputFiles[0].text;
if (process.argv.includes("--check")) {
  if (await readFile(output, "utf8") !== content) throw new Error("Webhook quote bundle is stale; run npm run quote:prepare");
} else await writeFile(output, content);
console.log(`Webhook quote bundle ${process.argv.includes("--check") ? "verified" : "built"} (${content.length} bytes)`);
